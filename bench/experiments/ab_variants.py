"""A/B benchmark of code variants, each described by a patch file.

For each variant: create a temporary git worktree at HEAD, apply the patch
(the "head" variant applies none), build ob_bench in Release, and keep the
binary. Then run all variants interleaved (round by round, every variant once
per round, each in a fresh process) and write a RESULTS.md next to the
patches with the median and min..max per variant.

Used for the upgrade F layout experiments:
    python3 bench/experiments/ab_variants.py bench/experiments/layout \
        --books pool_array,pool_map --rounds 7

Generated output only; never edit the RESULTS.md it writes by hand.
"""
from __future__ import annotations

import argparse
import json
import shutil
import statistics
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "bench"))
import run_all  # noqa: E402  (machine and build info helpers)

WORKLOADS = ("py_parity", "shape", "wide")


def build_variant(patch: Path | None, out: Path) -> None:
    tmp = Path(tempfile.mkdtemp(prefix="ob_ab_"))
    tree = tmp / "src"
    subprocess.check_call(["git", "-C", str(ROOT), "worktree", "add", "--detach", "-q", str(tree), "HEAD"])
    try:
        if patch is not None:
            subprocess.check_call(["git", "-C", str(tree), "apply", str(patch)])
        build = tmp / "build"
        subprocess.check_call(["cmake", "-S", str(tree), "-B", str(build), "-DCMAKE_BUILD_TYPE=Release",
                               "-DOB_BUILD_TESTS=OFF"], stdout=subprocess.DEVNULL)
        subprocess.check_call(["cmake", "--build", str(build), "--target", "ob_bench", "-j"],
                              stdout=subprocess.DEVNULL)
        shutil.copy(build / "bench" / "ob_bench", out)
    finally:
        subprocess.check_call(["git", "-C", str(ROOT), "worktree", "remove", "--force", str(tree)])
        shutil.rmtree(tmp, ignore_errors=True)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("experiment_dir")
    ap.add_argument("--books", default="pool_array,pool_map")
    ap.add_argument("--rounds", type=int, default=7)
    args = ap.parse_args()
    exp = Path(args.experiment_dir).resolve()
    patches = sorted(exp.glob("*.patch"))
    books = args.books.split(",")

    bins = Path(tempfile.mkdtemp(prefix="ob_ab_bins_"))
    variants = {"head": None, **{p.stem: p for p in patches}}
    for name, patch in variants.items():
        print(f"building {name}", file=sys.stderr)
        build_variant(patch, bins / name)

    machine = run_all.machine_info()
    sha = run_all.sh(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT)
    results: dict = {}
    for wl in WORKLOADS:
        for rnd in range(args.rounds):
            print(f"{wl} round {rnd + 1}/{args.rounds}", file=sys.stderr)
            for book in books:
                for name in variants:
                    out = subprocess.check_output([str(bins / name), "--book", book, "--workload", wl,
                                                   "--runs", "1"], cwd=ROOT, text=True)
                    results.setdefault((wl, book, name), []).append(
                        json.loads(out)["orders_per_sec_runs"][0])
    shutil.rmtree(bins, ignore_errors=True)

    L = [
        f"# A/B results: {exp.name}",
        "",
        "Generated by `python3 bench/experiments/ab_variants.py "
        f"{exp.relative_to(ROOT)} --books {args.books} --rounds {args.rounds}`. Do not edit by hand.",
        "",
        f"- Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- Base commit (`head`): {sha}; every other variant is `head` plus its `.patch` file here",
        f"- CPU: {machine['cpu']}; load average at start: {machine['loadavg_at_start']}",
        f"- Build: CMake Release, same flags as bench/RESULTS.md",
        f"- {args.rounds} interleaved rounds; every variant runs once per round in a fresh process",
        "",
        "orders/sec, median across rounds (min .. max):",
        "",
        "| Workload | Book | " + " | ".join(variants) + " |",
        "|---|---|" + "---:|" * len(variants),
    ]
    for wl in WORKLOADS:
        for book in books:
            cells = []
            for name in variants:
                xs = results[(wl, book, name)]
                cells.append(f"{statistics.median(xs) / 1e6:.1f}M ({min(xs) / 1e6:.1f} .. {max(xs) / 1e6:.1f})")
            L.append(f"| {wl} | {book} | " + " | ".join(cells) + " |")
    L.append("")
    (exp / "RESULTS.md").write_text("\n".join(L))
    print(f"wrote {exp / 'RESULTS.md'}", file=sys.stderr)


if __name__ == "__main__":
    main()
