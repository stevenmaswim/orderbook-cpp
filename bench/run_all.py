"""Run every benchmark and regenerate bench/RESULTS.md and bench/results.json.

RESULTS.md is generated by this script only. Never edit it by hand, and
never quote a number in the README or docs that is not in it.

Usage (from the repo root, after `cmake --build --preset release`):
    python3 bench/run_all.py [--books baseline,...] [--runs 5] [--skip-python]

Requires a Release build (checked) and, for the Python comparison, the
Python engine repo next to this one with its venv (--py-repo, --py-python).
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shlex
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build" / "release"
BENCH = BUILD / "bench" / "ob_bench"
ALL_BOOKS = ["baseline", "intrusive_map", "intrusive_array"]
SHAPE_SEED = 1
SHAPE_SUBMITS = 1_000_000


def sh(cmd: list[str], **kw) -> str:
    return subprocess.check_output(cmd, text=True, **kw).strip()


def bench(*args: str) -> dict:
    out = sh([str(BENCH), *args], cwd=ROOT)
    return json.loads(out.splitlines()[-1])


def machine_info() -> dict:
    info = {"os": platform.platform(), "arch": platform.machine()}
    if sys.platform == "darwin":
        info["cpu"] = sh(["sysctl", "-n", "machdep.cpu.brand_string"])
        info["cores"] = (f"{sh(['sysctl', '-n', 'hw.perflevel0.physicalcpu'])} performance + "
                         f"{sh(['sysctl', '-n', 'hw.perflevel1.physicalcpu'])} efficiency")
        info["cache_line"] = sh(["sysctl", "-n", "hw.cachelinesize"])
    else:
        model = [l for l in Path("/proc/cpuinfo").read_text().splitlines() if l.startswith("model name")]
        info["cpu"] = model[0].split(":", 1)[1].strip() if model else platform.processor()
        info["cores"] = sh(["nproc"])
    return info


def build_info() -> dict:
    cache = (BUILD / "CMakeCache.txt").read_text()
    build_type = re.search(r"^CMAKE_BUILD_TYPE:\w+=(.*)$", cache, re.M).group(1)
    if build_type != "Release":
        sys.exit(f"build/release is a {build_type!r} build; benchmarks need Release")
    compiler = re.search(r"^CMAKE_CXX_COMPILER:\w+=(.*)$", cache, re.M).group(1)
    version = sh([compiler, "--version"]).splitlines()[0]
    # The exact compile line CMake used for the bench driver, minus paths.
    cmds = json.loads((BUILD / "compile_commands.json").read_text())
    line = next(c["command"] for c in cmds if c["file"].endswith("bench_main.cpp"))
    tokens = shlex.split(line)[1:]  # drop the compiler itself
    flags, skip_next = [], False
    for tok in tokens:
        if skip_next:
            skip_next = False
            continue
        if tok in ("-o", "-isystem"):  # these take a path argument
            skip_next = True
            continue
        if tok == "-c" or tok.startswith("-I") or not tok.startswith("-") and "/" in tok:
            continue  # include paths and the source file are not codegen flags
        flags.append(tok)
    sha = sh(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT)
    dirty = sh(["git", "status", "--porcelain", "--untracked-files=no"], cwd=ROOT) != ""
    return {"compiler": version, "flags": " ".join(flags), "git": sha + (" (uncommitted changes)" if dirty else "")}


def fmt(n: float) -> str:
    return f"{n:,.0f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--books", default=",".join(ALL_BOOKS))
    ap.add_argument("--runs", type=int, default=5)
    ap.add_argument("--py-repo", default=str(ROOT.parent / "Order_book_project"))
    ap.add_argument("--py-python", default=str(ROOT.parent / "Order_book_project/.venv/bin/python3.11"))
    ap.add_argument("--skip-python", action="store_true")
    ap.add_argument("--out", default=str(ROOT / "bench"), help="directory for RESULTS.md etc.")
    args = ap.parse_args()
    books = args.books.split(",")
    runs = str(args.runs)
    out = Path(args.out).resolve()
    (out / "data").mkdir(parents=True, exist_ok=True)

    build = build_info()
    machine = machine_info()
    timer = bench("--mode", "timer")
    expected = json.loads((ROOT / "bench/py_parity/py_parity_expected.json").read_text())

    results: dict = {"build": build, "machine": machine, "timer": timer, "throughput": [], "latency": []}
    shape_args = ["--seed", str(SHAPE_SEED), "--submits", str(SHAPE_SUBMITS)]
    shape_states = {}
    for book in books:
        for wl in ("py_parity", "shape", "wide"):
            extra = shape_args if wl != "py_parity" else []
            print(f"throughput {book} {wl}", file=sys.stderr)
            t = bench("--mode", "throughput", "--book", book, "--workload", wl, "--runs", runs, *extra)
            # Correctness gate: a fast wrong book is worthless.
            state = {k: t[k] for k in ("trades", "traded_qty", "resting_orders", "bids", "asks")}
            if wl == "py_parity":
                want = {k: expected[k] for k in state}
                if state != want:
                    sys.exit(f"{book} end state on py_parity differs from the Python engine's")
            else:
                shape_states.setdefault(wl, {})[book] = state
            results["throughput"].append(t)
            print(f"latency {book} {wl}", file=sys.stderr)
            hist = out / f"data/latency_hist_{book}_{wl}.csv"
            results["latency"].append(bench("--mode", "latency", "--book", book, "--workload", wl,
                                            "--runs", runs, "--hist-csv", str(hist), *extra))
    for wl, states in shape_states.items():
        if len({json.dumps(s, sort_keys=True) for s in states.values()}) > 1:
            sys.exit(f"books disagree on the end state of the {wl} workload")

    py = None
    if not args.skip_python:
        print("python replay", file=sys.stderr)
        py = json.loads(sh([args.py_python, str(ROOT / "bench/py_parity/replay.py"),
                            "--py-repo", args.py_repo, "--runs", runs],
                           env={"PYTHONDONTWRITEBYTECODE": "1", "PATH": "/usr/bin:/bin"}))
        if (py["trades"], py["traded_qty"]) != (expected["trades"], expected["traded_qty"]):
            sys.exit("Python replay did not reproduce the recorded trades")
        results["python"] = py

    (out / "results.json").write_text(json.dumps(results, indent=1) + "\n")
    write_markdown(out, results, expected, books, py, args.runs)
    print(f"wrote {out}/RESULTS.md and results.json", file=sys.stderr)


def write_markdown(out: Path, r: dict, expected: dict, books: list[str], py: dict | None,
                   runs: int) -> None:
    m, b, t = r["machine"], r["build"], r["timer"]
    L = [
        "# Benchmark results",
        "",
        "Generated by `python3 bench/run_all.py` from the repo root. Do not edit by hand.",
        "",
        *(["**Generated on a shared CI virtual machine: noisy, CPU not controlled. "
           "Not a headline number.**", ""] if os.environ.get("CI") else []),
        "## Setup",
        "",
        "| | |",
        "|---|---|",
        f"| Generated | {datetime.now(timezone.utc).isoformat(timespec='seconds')} |",
        f"| Git | {b['git']} |",
        f"| CPU | {m['cpu']} ({m['cores']}) |",
        f"| OS | {m['os']} |",
        f"| Compiler | {b['compiler']} |",
        f"| Flags | `{b['flags']}` |",
        f"| Thread placement | {r['throughput'][0]['pinning']} |",
        f"| Timer | `{t['clock']}`: smallest observed step {t['min_nonzero_step_ns']} ns, "
        f"{t['cost_per_read_ns']} ns per read |",
        f"| Runs | {runs} timed runs after 1 discarded warmup run; tables show the median |",
        "",
        "## Workloads",
        "",
        f"- **py_parity**: the Python engine's own benchmark op stream, recorded by "
        f"`bench/py_parity/export_trace.py` running `demo.trader` unchanged (seeds 42, 43, 44, "
        f"single-threaded) against the Python engine at commit {expected['source_repo_commit']}. "
        f"{expected['ops']:,} ops = {expected['submits']:,} submits (90% limit over a 101-tick band, "
        f"10% market, qty 1..100) + {expected['cancels']:,} cancels. "
        f"`bench/py_parity/py_parity.bin`, sha256 `{expected['trace_sha256'][:16]}...`. "
        "One run = 200 back-to-back replays, each on a fresh book (throughput) or 20 (latency).",
        f"- **shape**: the same distributions generated in C++ (`bench/workloads.hpp`), "
        f"{SHAPE_SUBMITS:,} submits, seed {SHAPE_SEED}. One replay per run.",
        f"- **wide**: the shape workload with prices spread over the whole 20,000-tick band "
        f"instead of 101 ticks, so the book is sparse. Same size and seed.",
        "",
        "Every book's end state on py_parity (trades, traded qty, resting orders, every price "
        "level's qty) matched the Python engine's recorded end state, and all books matched each "
        "other on shape and wide. The script refuses to write this file otherwise.",
        "",
        "## Throughput",
        "",
        "orders/sec counts submits only, divided by wall time that also includes the cancels "
        "(the Python repo's definition). ops/sec counts submits + cancels.",
        "",
        "| Book | Workload | orders/sec (median) | ops/sec (median) | orders/sec min .. max |",
        "|---|---|---:|---:|---:|",
    ]
    for x in r["throughput"]:
        o = x["orders_per_sec_runs"]
        L.append(f"| {x['book']} | {x['workload']} | {fmt(x['orders_per_sec_median'])} | "
                 f"{fmt(x['ops_per_sec_median'])} | {fmt(min(o))} .. {fmt(max(o))} |")
    if py:
        L += [
            "",
            "## Against the Python engine (same machine, same op stream)",
            "",
            f"Python {py['python']}, `bench/py_parity/replay.py`: ops decoded before timing, each "
            f"replay on a fresh `MatchingEngine` (RLock included), {py['reps_per_run']} replays per run.",
            "",
            "| Engine | orders/sec (median) | vs Python |",
            "|---|---:|---:|",
            f"| Python engine | {fmt(py['orders_per_sec_median'])} | 1.0x |",
        ]
        for x in r["throughput"]:
            if x["workload"] == "py_parity":
                ratio = x["orders_per_sec_median"] / py["orders_per_sec_median"]
                L.append(f"| C++ {x['book']} | {fmt(x['orders_per_sec_median'])} | {ratio:,.1f}x |")
        L += [
            "",
            "The Python repo's own `benchmarks/RESULTS.md` reports a different quantity "
            "(single-threaded median 382,246 orders/sec) because its timed loop also runs "
            "`demo.trader`'s random-number generation. It is not the comparison point above.",
        ]
    L += [
        "",
        "## Latency per operation",
        "",
        "One `steady_clock` read before and after each op. Each value is the median over the "
        "runs of that run's percentile (nearest rank). Samples include the cost of one clock "
        f"read (about {t['cost_per_read_ns']} ns), and on this machine the clock moves in "
        f"steps of {t['min_nonzero_step_ns']} ns, so sub-step differences are not visible: "
        "treat small values as buckets, not exact times. `rejected` is mostly cancels of "
        "orders that had already filled: like the Python workload, the generator cancels ids it "
        "once saw rest.",
        "",
        "| Book | Workload | Op kind | samples/run | p50 ns | p99 ns | p99.9 ns | max ns |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for x in r["latency"]:
        for kind, v in x["kinds"].items():
            L.append(f"| {x['book']} | {x['workload']} | {kind} | {v['samples_per_run']:,} | "
                     f"{fmt(v['p50_ns'])} | {fmt(v['p99_ns'])} | {fmt(v['p999_ns'])} | {fmt(v['max_ns'])} |")
    L += [
        "",
        "## What this does not measure",
        "",
        "- One thread, one instrument, in-process calls: no network, no parsing, no queueing.",
        "- Throughput numbers are single-threaded matching speed. No thread count produced them.",
        "- macOS cannot hard-pin a thread to a core; the QoS hint above is all that was applied.",
        "",
    ]
    (out / "RESULTS.md").write_text("\n".join(L))


if __name__ == "__main__":
    main()
